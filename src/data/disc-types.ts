export interface DISCScores {
  scores: Record<string, number>;
  maxScore: number;
}

/**
 * Calculate DISC scores for all types based on answers
 * Supports most_least format: most = +2 points, least = -1 point
 * Returns scores for all types to display comprehensive results
 */
export function calculateDISCScores(answers: Record<string, string | number | { most: string; least: string }>): DISCScores {
  const scores: Record<string, number> = {
    D: 0,
    I: 0,
    S: 0,
    C: 0,
  };

  // Process each answer
  Object.values(answers).forEach((answer) => {
    if (typeof answer === 'object' && answer !== null && 'most' in answer && 'least' in answer) {
      // Most_least format: most = +2, least = -1
      if (answer.most in scores) {
        scores[answer.most] += 2;
      }
      if (answer.least in scores) {
        scores[answer.least] -= 1;
      }
    } else if (typeof answer === 'string' && answer in scores) {
      // Legacy binary format support
      scores[answer]++;
    }
  });

  // Find max score for the total
  const maxScore = Math.max(...Object.values(scores));

  return { scores, maxScore };
}

/**
 * @deprecated Use calculateDISCScores for new implementations
 * Calculate DISC type based on answers (legacy function for compatibility)
 */
export function calculateDISCType(answers: Record<string, string | number | { most: string; least: string }>): DISCTypeData {
  const { scores } = calculateDISCScores(answers);

  // Find the type with the highest score
  let maxScore = -Infinity;
  let dominantType = 'I'; // Default to I if no clear winner

  for (const [type, score] of Object.entries(scores)) {
    if (score > maxScore) {
      maxScore = score;
      dominantType = type;
    }
  }

  return discTypes[dominantType] || discTypes['I'];
}
