// Function to calculate MBTI type from answers
export function calculateMBTIType(answers: Record<string, string | number>): MBTITypeData & { variant: 'T' | 'A'; fullCode: string } {
  const scores = {
    E: 0,
    I: 0,
    S: 0,
    N: 0,
    T: 0,
    F: 0,
    J: 0,
    P: 0
  };

  // Sum up scores for each dimension
  Object.values(answers).forEach((answer) => {
    if (typeof answer === 'string') {
      // Check if it's a score format like "E:2" or just a letter like "E"
      if (answer.includes(':')) {
        // Likert scale format: "E:2" means 2 points for E
        const [dimension, scoreStr] = answer.split(':');
        const score = parseInt(scoreStr, 10);
        if (dimension in scores) {
          scores[dimension as keyof typeof scores] += score;
        }
      } else if (answer in scores) {
        // Legacy binary format: just "E" means 1 point
        scores[answer as keyof typeof scores]++;
      }
    }
  });

  // Determine type based on which side has more points
  const type =
    (scores.E > scores.I ? 'E' : 'I') +
    (scores.S > scores.N ? 'S' : 'N') +
    (scores.T > scores.F ? 'T' : 'F') +
    (scores.J > scores.P ? 'J' : 'P');

  // Determine turbulence: if person has more I, F, or P traits, they tend to be more turbulent
  const turbulenceScore = scores.I + scores.F + scores.P;
  const assertiveScore = scores.E + scores.T + scores.J;
  const variant: 'T' | 'A' = turbulenceScore > assertiveScore ? 'T' : 'A';

  const baseType = mbtiTypes[type] || mbtiTypes['INFP'];
  const fullCode = `${type}-${variant}`;

  // Use turbulent or assertive description if available
  let description = baseType.description;
  if (variant === 'T' && baseType.turbulentDescription) {
    description = baseType.turbulentDescription;
  } else if (variant === 'A' && baseType.assertiveDescription) {
    description = baseType.assertiveDescription;
  }

  return {
    ...baseType,
    description,
    variant,
    fullCode,
    code: fullCode
  };
}
