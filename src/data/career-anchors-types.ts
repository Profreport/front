/**
 * Career Anchors Assessment (Edgar Schein)
 * Identifies dominant career values and motivations
 * Classic version with 40 questions on Likert scale (1-10)
 */

export interface CareerAnchorData {
  code: string;
  title: string;
  description: string;
  characteristics: string[];
  professions: string[];
  strengths: string[];
  recommendations: string[];
}

export interface CareerAnchorQuestion {
  id: string;
  anchor: string; // TF, GM, AU, SE, EC, SV, CH, LS
  textAdult: string; // For adults with work experience
  textTeen: string; // For teenagers/students
}

export interface CareerAnchorResult {
  scores: Record<string, number>; // Average scores (0-10) for each anchor
  dominantAnchors: Array<{ anchor: CareerAnchorData; score: number }>; // All anchors sorted by score
  primaryAnchor: CareerAnchorData; // Highest scoring anchor
}

