/**
 * Calculate career anchors based on Likert scale answers (1-10)
 * Returns all anchors with average scores sorted by score descending
 */
export function calculateCareerAnchor(answers: Record<string, string | number>): CareerAnchorResult {
  // Initialize scores - sum of ratings for each anchor
  const anchorScores: Record<string, number[]> = {
    TF: [],
    GM: [],
    AU: [],
    SE: [],
    EC: [],
    SV: [],
    CH: [],
    LS: [],
  };

  // Group answers by anchor type based on question ID
  Object.entries(answers).forEach(([questionId, answer]) => {
    const question = careerAnchorQuestions.find(q => q.id === questionId);
    if (question && typeof answer === 'number') {
      anchorScores[question.anchor].push(answer);
    }
  });

  // Calculate average score for each anchor
  const averageScores: Record<string, number> = {};
  Object.entries(anchorScores).forEach(([anchor, scores]) => {
    if (scores.length > 0) {
      const sum = scores.reduce((acc, score) => acc + score, 0);
      averageScores[anchor] = Number((sum / scores.length).toFixed(1));
    } else {
      averageScores[anchor] = 0;
    }
  });

  // Sort anchors by score descending
  const sortedAnchors = Object.entries(averageScores)
    .sort(([, scoreA], [, scoreB]) => scoreB - scoreA)
    .map(([anchorCode, score]) => ({
      anchor: careerAnchors[anchorCode],
      score,
    }));

  // Primary anchor is the highest scoring one
  const primaryAnchor = sortedAnchors[0]?.anchor || careerAnchors['TF'];

  return {
    scores: averageScores,
    dominantAnchors: sortedAnchors,
    primaryAnchor,
  };
}
