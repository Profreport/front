export interface InterestMapScores {
  scores: Record<string, number>;
  dominantSpheres: Array<{
    sphere: InterestSphere;
    score: number;
    maxScore: number;
    percentage: number;
    level: string;
  }>;
}

/**
 * Calculate interest map scores for all spheres based on answers
 * Each answer is rated 1-5 (1 = not interested, 5 = very interested)
 * Returns comprehensive results for all spheres
 */
export function calculateInterestMapScores(
  answers: Record<string, string | number>
): InterestMapScores {
  const scores: Record<string, number> = {
    IT: 0,
    NATURE: 0,
    TECH: 0,
    MEDICINE: 0,
    ART: 0,
    LITERATURE: 0,
    EDUCATION: 0,
    BUSINESS: 0,
    LAW: 0,
    SOCIAL: 0,
    SPORT: 0,
    DESIGN: 0,
    LOGISTICS: 0,
    CULINARY: 0,
    MANAGEMENT: 0,
  };

  // Sum up scores for each sphere (6 questions per sphere)
  Object.entries(answers).forEach(([questionId, answer]) => {
    // Extract sphere code from question ID (e.g., "q_IT_1" -> "IT")
    const match = questionId.match(/^q_([A-Z]+)_\d+$/);
    if (match && match[1] in scores) {
      const sphereCode = match[1];
      const score = typeof answer === 'number' ? answer : parseInt(String(answer), 10);
      if (!isNaN(score)) {
        scores[sphereCode] += score;
      }
    }
  });

  // Calculate dominant spheres with detailed information
  const maxScore = 30; // 6 questions × 5 points max
  const dominantSpheres = Object.entries(scores)
    .map(([code, score]) => {
      const sphere = interestSpheres[code];
      const percentage = Math.round((score / maxScore) * 100);

      let level = 'Низкий интерес';
      if (percentage >= 80) level = 'Очень высокий интерес';
      else if (percentage >= 60) level = 'Высокий интерес';
      else if (percentage >= 40) level = 'Средний интерес';
      else if (percentage >= 20) level = 'Низкий интерес';
      else level = 'Очень низкий интерес';

      return {
        sphere,
        score,
        maxScore,
        percentage,
        level,
      };
    })
    .sort((a, b) => b.score - a.score);

  return { scores, dominantSpheres };
}
