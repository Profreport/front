export interface KlimovScores {
  scores: Record<string, number>;
  maxScore: number;
}

/**
 * Calculate Klimov scores for all types based on answers
 * Each answer is a type code (P, T, CH, Z, KH)
 * Returns scores for all types to display comprehensive results
 */
export function calculateKlimovScores(answers: Record<string, string | number>): KlimovScores {
  const scores: Record<string, number> = {
    P: 0,
    T: 0,
    CH: 0,
    Z: 0,
    KH: 0,
  };

  // Count answers for each type
  Object.values(answers).forEach((answer) => {
    if (typeof answer === 'string' && answer in scores) {
      scores[answer]++;
    }
  });

  // Find max score for the total
  const maxScore = Math.max(...Object.values(scores));

  return { scores, maxScore };
}

/**
 * @deprecated Use calculateKlimovScores for new implementations
 * Calculate Klimov type based on answers (legacy function for compatibility)
 */
export function calculateKlimovType(answers: Record<string, string | number>): KlimovTypeData {
  const { scores } = calculateKlimovScores(answers);

  // Find the type with the highest score
  let maxScore = 0;
  let dominantType = 'CH'; // Default to CH if no clear winner

  for (const [type, score] of Object.entries(scores)) {
    if (score > maxScore) {
      maxScore = score;
      dominantType = type;
    }
  }

  return klimovTypes[dominantType] || klimovTypes['CH'];
}
