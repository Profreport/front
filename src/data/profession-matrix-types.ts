/**
 * Calculate profession matrix result based on answers
 * Questions determine preferences for work object and activity type
 */
export function calculateProfessionMatrix(
  answers: Record<string, string | number>
): ProfessionMatrixResult {
  // Count votes for each work object
  const objectScores: Record<string, number> = {
    PEOPLE: 0,
    INFO: 0,
    TECH: 0,
    ART: 0,
    NATURE: 0,
  };

  // Count votes for each activity type
  const activityScores: Record<string, number> = {
    EXEC: 0,
    CREATIVE: 0,
    MANAGE: 0,
  };

  // Process answers
  Object.entries(answers).forEach(([questionId, answer]) => {
    if (questionId.startsWith('object_')) {
      // Object questions
      const answerStr = String(answer);
      if (answerStr in objectScores) {
        objectScores[answerStr]++;
      }
    } else if (questionId.startsWith('activity_')) {
      // Activity questions
      const answerStr = String(answer);
      if (answerStr in activityScores) {
        activityScores[answerStr]++;
      }
    }
  });

  // Find dominant object
  let maxObjectScore = 0;
  let dominantObject = 'INFO';
  for (const [obj, score] of Object.entries(objectScores)) {
    if (score > maxObjectScore) {
      maxObjectScore = score;
      dominantObject = obj;
    }
  }

  // Find dominant activity
  let maxActivityScore = 0;
  let dominantActivity = 'EXEC';
  for (const [activity, score] of Object.entries(activityScores)) {
    if (score > maxActivityScore) {
      maxActivityScore = score;
      dominantActivity = activity;
    }
  }

  // Get result from matrix
  return professionMatrix[dominantObject][dominantActivity];
}
